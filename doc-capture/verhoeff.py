def verify_aadhaar(number: str) -> bool:
    """
    Returns True if the 12-digit Aadhaar number passes the Verhoeff checksum.
    The number must consist of exactly 12 digits.
    """
    cleaned = "".join(c for c in number if c.isdigit())
    if len(cleaned) != 12:
        return False
        
    c = 0
    reversed_digits = [int(x) for x in reversed(cleaned)]
    
    for i, digit in enumerate(reversed_digits):
        c = d[c][p[i % 8][digit]]
        
    return c == 0
